"""Synthesize 30 realistic day-to-day queries against the sw30labs wiki.

Split:
  - 10 narrow      (answerable from one page)
  - 10 branch      (one subtree; e.g., one category folder)
  - 10 cross-branch (needs material from >1 subtree)

Queries are generated by Claude Opus 4.6 in three batches (one per difficulty).
Ground-truth source paths are captured at synthesis for the judge.
"""
from __future__ import annotations
import os, json, random, time
from pathlib import Path
import anthropic

MODEL = "claude-opus-4-6"
OPUS_IN = 15.0
OPUS_OUT = 75.0

INSTRUCTIONS = """You are generating an eval set for a retrieval-system benchmark on the sw30labs LLM wiki.

Below is the full sitemap of the wiki (every page, title, and summary), followed by the full content of a few representative pages for grounding.

Generate exactly {n} queries of type {category}.

{category_def}

Constraints:
- Queries must be natural, day-to-day questions someone working with this org would actually ask — NOT trivia, NOT meta-questions about the wiki itself.
- Every query must be answerable from the wiki content shown.
- For each query, provide the minimal set of ground-truth source paths that contain the answer.
- Do NOT quote wiki text verbatim in the query; rephrase.
- Return a JSON array. Each element has: `query` (string), `sources` (list of paths), `rationale` (one-line internal note).

Return ONLY the JSON array, nothing else."""

CATEGORY_DEFS = {
    "narrow": "NARROW: the answer lives on exactly one page. Each query.sources has exactly 1 element.",
    "branch": "BRANCH: the answer requires reading a single subtree / category (e.g., all pages under wiki/ai-security/). Each query.sources has 2-4 elements all under the same top-level folder or category.",
    "cross-branch": "CROSS-BRANCH: the answer requires material from pages in multiple different subtrees (e.g., one page from wiki/ai-security/ and one from wiki/agentic-frameworks/). Each query.sources has 2-4 elements spanning >= 2 top-level folders.",
}


def _sample_pages(corpus_root: Path, sitemap: list[dict], k_per_group: int = 2, seed: int = 42) -> str:
    """Pick a handful of pages across categories so Opus has grounding."""
    rng = random.Random(seed)
    groups: dict[str, list[dict]] = {}
    for e in sitemap:
        top = e["path"].split("/", 1)[0]
        groups.setdefault(top, []).append(e)
    picks = []
    for top, items in groups.items():
        rng.shuffle(items)
        picks.extend(items[:k_per_group])
    out = []
    for e in picks:
        body = (corpus_root / e["path"]).read_text(encoding="utf-8", errors="ignore")
        # truncate huge pages
        if len(body) > 4000:
            body = body[:4000] + "\n... [truncated]"
        out.append(f"=== {e['path']} ===\n{body}")
    return "\n\n".join(out)


def synthesize(corpus_root: Path, sitemap_path: Path, out_path: Path, per_category: int = 10) -> dict:
    sitemap_md = sitemap_path.read_text()
    sitemap_entries = json.loads((sitemap_path.parent / "entries.json").read_text())
    groundings = _sample_pages(corpus_root, sitemap_entries)

    ac = anthropic.Anthropic()
    all_queries = []
    usage = {"input": 0, "output": 0}

    for category in ["narrow", "branch", "cross-branch"]:
        prompt = f"""{INSTRUCTIONS.format(n=per_category, category=category, category_def=CATEGORY_DEFS[category])}

=========== SITEMAP ===========
{sitemap_md}

=========== SAMPLE PAGES ===========
{groundings}
"""
        r = ac.messages.create(
            model=MODEL,
            max_tokens=4000,
            temperature=0.4,
            messages=[{"role": "user", "content": prompt}],
        )
        usage["input"] += r.usage.input_tokens
        usage["output"] += r.usage.output_tokens
        text = r.content[0].text.strip()
        # parse json (tolerate ```json fences)
        if text.startswith("```"):
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        batch = json.loads(text.strip())
        for q in batch:
            q["category"] = category
        all_queries.extend(batch)
        print(f"  {category}: {len(batch)} queries")

    # finalize
    for i, q in enumerate(all_queries):
        q["id"] = f"q{i:02d}"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        for q in all_queries:
            f.write(json.dumps(q) + "\n")

    cost = usage["input"] / 1_000_000 * OPUS_IN + usage["output"] / 1_000_000 * OPUS_OUT
    meta = {
        "n_queries": len(all_queries),
        "by_category": {c: sum(1 for q in all_queries if q["category"] == c) for c in CATEGORY_DEFS},
        "synth_input_tokens": usage["input"],
        "synth_output_tokens": usage["output"],
        "synth_cost_usd": round(cost, 4),
        "model": MODEL,
    }
    (out_path.parent / "synth_meta.json").write_text(json.dumps(meta, indent=2))
    return meta


if __name__ == "__main__":
    import sys
    corpus = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("corpus")
    sitemap = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("wiki/sitemap/sitemap.md")
    out = Path(sys.argv[3]) if len(sys.argv) > 3 else Path("eval/queries.jsonl")
    meta = synthesize(corpus, sitemap, out)
    print(json.dumps(meta, indent=2))
