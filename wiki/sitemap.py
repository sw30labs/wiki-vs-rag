"""Build the hierarchical sitemap the navigation agent sees up-front.

Produces a compact tree: `path — title — one-sentence summary`
Summaries are pulled from front-matter or the first non-header paragraph
(NOT generated by an LLM — that would leak LLM cost into setup).
"""
from __future__ import annotations
import os, re, json, yaml
from pathlib import Path

FRONT_MATTER = re.compile(r"^---\n(.*?)\n---\n", re.S)


def _read_front_matter(text: str) -> dict:
    m = FRONT_MATTER.match(text)
    if not m:
        return {}
    try:
        return yaml.safe_load(m.group(1)) or {}
    except Exception:
        return {}


def _first_sentence(text: str, limit: int = 160) -> str:
    body = FRONT_MATTER.sub("", text).strip()
    # strip leading markdown header lines
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith("#") or s.startswith("```"):
            continue
        sent = re.split(r"(?<=[.!?])\s", s, maxsplit=1)[0]
        return sent[:limit].strip()
    return ""


def _title_from(path: Path, fm: dict, body: str) -> str:
    if "title" in fm:
        return str(fm["title"])
    for line in body.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem.replace("-", " ").replace("_", " ")


def build_sitemap(corpus_root: Path) -> list[dict]:
    entries = []
    for md in sorted(corpus_root.rglob("*.md")):
        if md.name.startswith("_"):
            continue
        text = md.read_text(encoding="utf-8", errors="ignore")
        fm = _read_front_matter(text)
        rel = str(md.relative_to(corpus_root))
        entries.append({
            "path": rel,
            "title": _title_from(md, fm, text),
            "summary": _first_sentence(text),
            "tags": fm.get("tags", []) if isinstance(fm.get("tags"), list) else [],
            "category": fm.get("category", ""),
        })
    return entries


def render_sitemap_markdown(entries: list[dict]) -> str:
    """Tree-ish rendering grouped by top-level folder."""
    groups: dict[str, list[dict]] = {}
    for e in entries:
        top = e["path"].split("/", 1)[0] if "/" in e["path"] else "(root)"
        groups.setdefault(top, []).append(e)
    lines = ["# sw30labs wiki — sitemap", ""]
    for top in sorted(groups):
        lines.append(f"## {top}/")
        for e in sorted(groups[top], key=lambda x: x["path"]):
            tag = f" [{','.join(e['tags'][:3])}]" if e["tags"] else ""
            summary = f" — {e['summary']}" if e["summary"] else ""
            lines.append(f"- `{e['path']}` — **{e['title']}**{tag}{summary}")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    import sys
    corpus = Path(sys.argv[1] if len(sys.argv) > 1 else "corpus")
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "wiki/sitemap")
    out.mkdir(parents=True, exist_ok=True)
    entries = build_sitemap(corpus)
    (out / "entries.json").write_text(json.dumps(entries, indent=2))
    md = render_sitemap_markdown(entries)
    (out / "sitemap.md").write_text(md)
    import tiktoken
    enc = tiktoken.get_encoding("cl100k_base")
    meta = {
        "n_entries": len(entries),
        "sitemap_tokens": len(enc.encode(md)),
        "corpus_root": str(corpus),
    }
    (out / "sitemap_meta.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps(meta, indent=2))
